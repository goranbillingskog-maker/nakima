// Nakima v1 clinic data layer.
// Static seed data — will be replaced by Lovable Cloud (Supabase) in a later
// iteration. Structure is designed so the DB migration is a straight mapping:
// one row per clinic, one row per (clinic, service) join, cities as a table.
//
// v1 scope: naprapat only, top 5 cities. Only Stockholm is populated with
// clinics; other cities render an "kommer snart" state.

export type ServiceSlug = "naprapat" | "kiropraktor" | "massage";

export type CitySlug =
  | "stockholm"
  | "goteborg"
  | "malmo"
  | "uppsala"
  | "vasteras";

export interface City {
  slug: CitySlug;
  name: string;
  region: string;
  // Short editorial intro used in city hero + meta description.
  intro: string;
}

export interface Clinic {
  slug: string;
  name: string;
  city: CitySlug;
  neighborhood: string;
  street: string;
  postal: string;
  services: ServiceSlug[];
  // Redaktionell one-liner about the clinic's profile.
  blurb: string;
  // 0–5, one decimal. Editorial score, not user reviews (those come in v2).
  rating: number;
  reviewCount: number;
  // Price range indicator: 1–3 ("kr", "kr kr", "kr kr kr").
  priceLevel: 1 | 2 | 3;
  // Public booking URL (affiliate slot). Null = "kontakta kliniken".
  bookingUrl: string | null;
  phone: string;
  // WGS84 coordinates (approx, from neighborhood centroid until per-clinic geocoding).
  lat?: number;
  lng?: number;
  featured?: boolean;
  // ISO date (YYYY-MM-DD) — when this clinic's record was last verified/edited.
  // Feeds sitemap <lastmod> per URL. Defaults to DATASET_UPDATED_AT if omitted.
  updatedAt?: string;
  // Optional enrichment fields (populated per clinic when available; page
  // falls back to editorial defaults when missing). Structured for LLM
  // extraction + rich MedicalBusiness schema.
  openingHours?: Partial<Record<
    "mon" | "tue" | "wed" | "thu" | "fri" | "sat" | "sun",
    string // "08:00–18:00" or "Stängt"
  >>;
  established?: number; // grundläggningsår
  languages?: string[]; // ["Svenska", "Engelska"]
  specialties?: string[]; // ["Idrottsskador", "Nack- och ryggsmärta"]
  paymentMethods?: string[]; // ["Swish", "Kort", "Faktura"]
  accessibility?: string[]; // ["Hiss", "Rullstolsanpassad"]
  website?: string;
}




