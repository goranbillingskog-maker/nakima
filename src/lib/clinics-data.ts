export function getCity(slug: string): City | undefined {
  return cities.find((c) => c.slug === slug);
}

export function getClinicsByCity(city: CitySlug, service: ServiceSlug): Clinic[] {
  return clinics
    .filter((c) => c.city === city && c.services.includes(service))
    .sort((a, b) => {
      if (a.featured && !b.featured) return -1;
      if (!a.featured && b.featured) return 1;
      return b.rating - a.rating;
    });
}

export function getClinicBySlug(city: CitySlug, slug: string): Clinic | undefined {
  return clinics.find((c) => c.city === city && c.slug === slug);
}

// Sibling clinics in the same neighborhood, excluding the current one. Used
// on detail pages for the "Fler kliniker i stadsdelen" rail.
export function getRelatedClinics(clinic: Clinic, limit = 3): Clinic[] {
  return clinics
    .filter(
      (c) =>
        c.city === clinic.city &&
        c.slug !== clinic.slug &&
        (c.neighborhood === clinic.neighborhood ||
          c.services.some((s) => clinic.services.includes(s))),
    )
    .sort((a, b) => {
      // Same-neighborhood first, then by rating.
      const aSame = a.neighborhood === clinic.neighborhood ? 1 : 0;
      const bSame = b.neighborhood === clinic.neighborhood ? 1 : 0;
      if (aSame !== bSame) return bSame - aSame;
      return b.rating - a.rating;
    })
    .slice(0, limit);
}

// Total clinics per city across ALL services in the seed data.
// Used for homepage city cards so the count reflects the actual dataset
// (later: swap for a `select count(*)` when clinics move to Lovable Cloud).
export function getCityClinicCount(city: CitySlug): number {
  return clinics.filter((c) => c.city === city).length;
}

